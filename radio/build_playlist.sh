  "radio/generated/murmur-soft-bell-chime-2433237892.murmur:content/test_midi/dune-chords.mid:25-soft-bell-chime"
  "radio/generated/murmur-soft-ep-chorus-1757860482.murmur:content/test_midi/demo-lfo-wobble.mid:26-soft-ep-chorus"
  "radio/generated/murmur-vintage-saw-pad-2375792245.murmur:content/test_midi/single-note.mid:27-vintage-saw-pad"
  "radio/generated/murmur-warm-breath-pad-3906066371.murmur:content/test_midi/pad-chords.mid:28-warm-breath-pad-2"
  "radio/generated/murmur-warm-drift-pad-3298602939.murmur:content/test_midi/tide_pad.mid:29-warm-drift-pad-2"
  "radio/generated/murmur-warm-organ-drone-1750320090.murmur:content/test_midi/bloom_pad.mid:30-warm-organ-drone"
  "radio/generated/murmur-warped-memory-3214856922.murmur:content/test_midi/dune-chords.mid:31-warped-memory"
)

mkdir -p "${OUT_DIR}/renders"
cd "$REPO_ROOT"

WAVS=()
for entry in "${PATCHES[@]}"; do
  IFS=':' read -r patch midi label <<< "$entry"
  out="${OUT_DIR}/renders/${label}.wav"
  echo "Rendering ${label} (${patch})..."
  "$RENDERER" --patch "$patch" --midi "$midi" --output "$out" --duration 45 --release-tail 3
  WAVS+=("$out")
done

# 4-second triangular crossfades, chained pairwise (ffmpeg's acrossfade only
# takes two inputs at a time) -- real overlap, not a hard cut, matching
# "crossfade between different arrangements" from the original ask. Built
# dynamically so the playlist length isn't hardcoded to 3 anymore.
echo "Crossfading ${#WAVS[@]} renders into ${OUT_DIR}/playlist.mp3..."

ffmpeg_inputs=()
for w in "${WAVS[@]}"; do
  ffmpeg_inputs+=(-i "$w")
done

filter=""
prev="[0]"
for ((i = 1; i < ${#WAVS[@]}; i++)); do
  next_label="[a$(printf '%02d' "$i")]"
  if (( i == ${#WAVS[@]} - 1 )); then
    next_label="[out]"
  fi
  filter+="${prev}[${i}]acrossfade=d=4:c1=tri:c2=tri${next_label};"
  prev="$next_label"
done
filter="${filter%;}"

ffmpeg -y \
  "${ffmpeg_inputs[@]}" \
  -filter_complex "$filter" \
  -map "[out]" -ar 44100 -c:a libmp3lame -b:a 192k "${OUT_DIR}/playlist.mp3"

echo "Done: ${OUT_DIR}/playlist.mp3"
